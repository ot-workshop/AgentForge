function openText(text, name) {
  try {
    const flow = parseFlow(text);
    if (!flow.nodes.length) throw new Error('文件里没有 nodes');
    state.flow = flow;
    state.sel = null;
    state.nextId = 1;
    render();
    say(`已打开 ${name}：${flow.nodes.length} 个节点、${flow.edges.length} 条边。导出后请再跑一次「校验」。`);
  } catch (err) {
    say(`打开失败：${err.message}`, true);
  }
}

el('btn-export').addEventListener('click', () => {
  const text = exportFlow(state.flow);
  const blob = new Blob([text], { type: 'text/yaml' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `${state.flow.id || 'flow'}.yaml`;
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  say(`已导出 ${a.download}\n\n${text}`);
});

el('btn-validate').addEventListener('click', async () => {
  const text = exportFlow(state.flow);
  const path = `${state.flow.id || 'ui-export'}.yaml`;
  if (!(await serverAvailable())) {
    say(`校验需要后端：本页是直接打开的文件，没有 /validate。\n\n两种办法：\n1) 在仓库根目录跑 node bin/forge.js serve，然后打开 http://127.0.0.1:8787/ui ；\n2) 把导出的 YAML 存成 ${path}，跑 node bin/forge.js validate ${path}\n\n当前导出内容：\n${text}`);
    return;
  }
  const r = await fetch('/validate', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ flow: text, path }) });
  const body = await r.json().catch(() => ({ errors: [{ code: `HTTP_${r.status}` }] }));
  if (!r.ok) {
    say(`校验请求失败（HTTP ${r.status}）：\n${JSON.stringify(body.errors ?? body, null, 2)}`, true);
    return;
  }
  const errs = body.errors ?? [];
  if (!errs.length) {
    say(`校验通过：{"errors":[]}\n\n${text}`);
    return;
  }
  say(`校验未通过（${errs.length} 条）：\n${JSON.stringify({ errors: errs }, null, 2)}`, true);
  highlightErrors(errs);
});

function highlightErrors(errs) {
  // Error paths are CLI-shaped (`flows/<file>#<nodeId>…`): locate the canvas
  // node by the path segment or by ids[], without renaming anything.
  const ids = new Set();
  for (const e of errs) {
    const m = /#([^.]+)/.exec(e.path ?? '');
    if (m) ids.add(m[1]);
    for (const id of e.ids ?? []) if (typeof id === 'string') ids.add(id);
    if (e.fix?.nodeId) ids.add(e.fix.nodeId);
  }
  if (!ids.size) return;
  for (const node of nodesLayer.children) if (ids.has(node.dataset.id)) node.style.outline = '2px solid #b91c1c';
}

// ---------- boot ----------
(async function boot() {
  const srv = await serverAvailable();
  banner(srv ? '' : '直接打开的本地页面：画布可用，导出用「导出 YAML」，校验请用 forge serve 或 CLI。');
  await loadBlocks();
  let samples = null;
  try {
    samples = await (await fetch(srv ? '/samples' : './samples.json')).json();
  } catch {
    samples = null;
  }
  const sel = el('sample');
  sel.append(new Option('选择样例…', ''));
  for (const s of samples?.samples ?? []) {
    const o = new Option(s.name, s.file);
    o.dataset.yaml = s.yaml;
    sel.append(o);
  }
  sel.addEventListener('change', () => {
    const opt = sel.options[sel.selectedIndex];
    if (opt?.dataset.yaml) openText(opt.dataset.yaml, opt.dataset.file);
  });
  render();
  // Read-only hooks for the headless self-check (no server-side equivalent):
  // open a flow, add blocks, connect, export.
  window.__canvas = {
    state,
    openText,
    exportText: () => exportFlow(state.flow),
    addBlocks: (refs) =>
      refs.map((ref) => addNode(state.blocks.find((b) => b.ref === ref), 40 + state.flow.nodes.length * 210, 60)).map((n) => n.id),
    link: (from, to) => {
      state.flow.edges.push({ id: null, from, to });
      render();
    },
    select: (sel) => {
      state.sel = sel;
      render();
    },
    setText: (value) => {
      output.textContent = String(value);
    },
  };
})();
