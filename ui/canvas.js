// AgentForge canvas (M2-A prototype). Interaction only: drag blocks onto the
// canvas, connect ports, export YAML. Execution stays in the existing
// orchestrator; validation goes through the repository's own validator
// (`forge serve` -> POST /validate, or `./bin/forge.js validate <file>`).
import { emptyFlow, parseFlow, exportFlow, semantics } from './flow-yaml.js';

const NODE_W = 190;
const NODE_H = 60;

const el = (id) => document.getElementById(id);
const canvas = el('canvas');
const nodesLayer = el('nodes');
const svg = el('edges');
const output = el('output');

const state = {
  flow: emptyFlow(),
  sel: null, // { kind: 'node', id } | { kind: 'edge', index }
  zoom: 1,
  blocks: [],
  warnings: [],
  linking: null, // { from, x, y }
  nextId: 1,
};

// ---------- small helpers ----------
function say(text, isErr = false) {
  output.textContent = text;
  output.classList.toggle('err', !!isErr);
}

function elt(tag, cls, text) {
  const n = document.createElement(tag);
  if (cls) n.className = cls;
  if (text !== undefined) n.textContent = text;
  return n;
}

function banner(text) {
  const b = el('banner');
  b.hidden = !text;
  b.textContent = text ?? '';
}

async function serverAvailable() {
  if (location.protocol === 'file:') return false;
  try {
    const r = await fetch('/blocks', { headers: { Accept: 'application/json' } });
    return r.ok;
  } catch {
    return false;
  }
}

// ---------- block library ----------
async function loadBlocks() {
  let data = null;
  try {
    const r = await fetch('/blocks');
    if (r.ok) data = await r.json();
  } catch {
    data = null;
  }
  if (!data) {
    // file:// page: use the copy generated by `node tools/canvas-sync.mjs`.
    try {
      data = await (await fetch('./blocks.json')).json();
    } catch {
      data = { blocks: [], warnings: ['无法读取块库（没有 serve，也没有 blocks.json）'] };
    }
  }
  state.blocks = data.blocks ?? [];
  state.warnings = data.warnings ?? [];
  renderPalette();
}

function renderPalette() {
  const list = el('blocks');
  list.replaceChildren();
  for (const b of state.blocks) {
    const li = elt('li');
    li.draggable = true;
    li.dataset.ref = b.ref;
    li.append(elt('span', 'name', b.ref), elt('small', '', `${b.agent ?? '—'} · in ${Object.keys(b.inputs ?? {}).join(',') || '—'}`));
    li.addEventListener('dragstart', (e) => {
      e.dataTransfer.setData('text/plain', b.ref);
      e.dataTransfer.effectAllowed = 'copy';
    });
    list.append(li);
  }
  if (!state.blocks.length) list.append(elt('li', 'muted', '块库为空'));
  const warn = el('block-warn');
  warn.hidden = !state.warnings.length;
  warn.textContent = state.warnings.length ? `块库提示（不影响画布）：\n${state.warnings.join('\n')}` : '';
}

// ---------- layout ----------
function nodeBox(id) {
  const n = state.flow.nodes.find((x) => x.id === id);
  if (!n) return null;
  return { x: n.ui.x, y: n.ui.y, w: NODE_W, h: NODE_H };
}

function autoLayout() {
  // Suggested placement only (stored as `ui:` in the export): columns by
  // longest-path depth, rows within a column.
  const ids = state.flow.nodes.map((n) => n.id);
  const indeg = new Map(ids.map((id) => [id, 0]));
  const succ = new Map(ids.map((id) => [id, []]));
  for (const e of state.flow.edges) {
    if (!indeg.has(e.to) || !indeg.has(e.from)) continue;
    indeg.set(e.to, indeg.get(e.to) + 1);
    succ.get(e.from).push(e.to);
  }
  const depth = new Map(ids.map((id) => [id, 0]));
  const seen = new Set();
  const walk = (id) => {
    if (seen.has(id)) return;
    seen.add(id);
    for (const t of succ.get(id)) {
      depth.set(t, Math.max(depth.get(t), depth.get(id) + 1));
      walk(t);
    }
  };
  for (const id of ids) if (indeg.get(id) === 0) walk(id);
  const cols = new Map();
  for (const id of ids) {
    const d = Math.min(depth.get(id) ?? 0, 8);
    const col = cols.get(d) ?? [];
    col.push(id);
    cols.set(d, col);
  }
  for (const [d, col] of cols) col.forEach((id, i) => place(id, 30 + d * 250, 40 + i * 110));
}

function place(id, x, y) {
  const n = state.flow.nodes.find((x2) => x2.id === id);
  if (!n) return;
  n.ui = { x: Math.max(0, Math.round(x)), y: Math.max(0, Math.round(y)) };
}

function ensureLayout() {
  for (const n of state.flow.nodes) if (!n.ui) n.ui = null;
  if (state.flow.nodes.some((n) => !n.ui)) autoLayout();
}

// ---------- rendering ----------
function render() {
  ensureLayout();
  const z = state.zoom;
  nodesLayer.style.transform = `scale(${z})`;
  nodesLayer.style.transformOrigin = '0 0';
  svg.style.transform = `scale(${z})`;
  svg.style.transformOrigin = '0 0';
  renderNodes();
  renderEdges();
  renderInspector();
}

function renderNodes() {
  nodesLayer.replaceChildren();
  for (const n of state.flow.nodes) {
    const node = elt('div', 'node');
    if (state.sel?.kind === 'node' && state.sel.id === n.id) node.classList.add('sel');
    node.dataset.id = n.id;
    node.style.left = `${n.ui.x}px`;
    node.style.top = `${n.ui.y}px`;
    const head = elt('header');
    head.append(elt('span', 'id', n.id));
    if (state.flow.entry === n.id) head.append(elt('span', 'badge entry', 'entry'));
    node.append(head);
    node.append(elt('div', 'body', n.uses || '（未选块）'));
    const pin = elt('div', 'port in');
    pin.title = '输入端：从另一个节点的输出拖过来';
    pin.dataset.in = n.id;
    const pout = elt('div', 'port out');
    pout.title = '输出端：拖到一个节点的输入端连边';
    pout.dataset.out = n.id;
    node.append(pin, pout);
    nodesLayer.append(node);
  }
  for (const node of nodesLayer.children) {
    const id = node.dataset.id;
    node.addEventListener('pointerdown', (e) => {
      if (e.target.classList.contains('port')) return;
      state.sel = { kind: 'node', id };
      if (state.flow.entry !== id && e.detail === 2 && e.target.closest('header')) {
        state.flow.entry = id;
      }
      render();
      startDrag(e, id, node);
    });
  }
}

function startDrag(e, id, node) {
  const n = state.flow.nodes.find((x) => x.id === id);
  const startX = e.clientX;
  const startY = e.clientY;
  const ox = n.ui.x;
  const oy = n.ui.y;
  const move = (ev) => {
    place(id, ox + (ev.clientX - startX) / state.zoom, oy + (ev.clientY - startY) / state.zoom);
    node.style.left = `${n.ui.x}px`;
    node.style.top = `${n.ui.y}px`;
    renderEdges();
  };
  const up = () => {
    window.removeEventListener('pointermove', move);
    window.removeEventListener('pointerup', up);
  };
  window.addEventListener('pointermove', move);
  window.addEventListener('pointerup', up);
}

function edgePath(a, b) {
  const ax = a.x + a.w;
  const ay = a.y + a.h / 2;
  const bx = b.x;
  const by = b.y + b.h / 2;
  const dx = Math.max(40, Math.abs(bx - ax) / 2);
  let d;
  if (bx >= ax) d = `M${ax},${ay} C${ax + dx},${ay} ${bx - dx},${by} ${bx},${by}`;
  else {
    // backward edge: route below the boxes
    const dip = Math.max(a.y, b.y) + a.h + 40;
    d = `M${ax},${ay} C${ax + 50},${dip} ${bx - 50},${dip} ${bx},${by}`;
  }
  return { d, mx: (ax + bx) / 2, my: (ay + by) / 2 };
}

function renderEdges() {
  for (const g of [...svg.querySelectorAll('g.edge')]) g.remove();
  state.flow.edges.forEach((e, idx) => {
    const a = nodeBox(e.from);
    const b = nodeBox(e.to);
    if (!a || !b) return;
    const { d, mx, my } = edgePath(a, b);
    const g = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    g.classList.add('edge');
    const hit = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    hit.setAttribute('d', d);
    hit.setAttribute('class', 'hit');
    hit.addEventListener('pointerdown', (ev) => {
      ev.stopPropagation();
      state.sel = { kind: 'edge', index: idx };
      render();
    });
    const line = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    line.setAttribute('d', d);
    line.setAttribute('class', `line${state.sel?.kind === 'edge' && state.sel.index === idx ? ' sel' : ''}`);
    line.setAttribute('marker-end', `url(#${state.sel?.kind === 'edge' && state.sel.index === idx ? 'arrow-sel' : 'arrow'})`);
    g.append(hit, line);
    if (e.on && typeof e.on === 'object') {
      const t = document.createElementNS('http://www.w3.org/2000/svg', 'text');
      t.setAttribute('x', String(mx));
      t.setAttribute('y', String(my - 6));
      t.setAttribute('text-anchor', 'middle');
      t.textContent = `${e.on.from ?? ''} ${e.on.status ?? ''}`.trim();
      g.append(t);
    }
    svg.append(g);
  });
  if (state.linking) {
    const a = nodeBox(state.linking.from);
    if (a) {
      const line = document.createElementNS('http://www.w3.org/2000/svg', 'path');
      line.setAttribute('d', `M${a.x + a.w},${a.y + a.h / 2} L${state.linking.x},${state.linking.y}`);
      line.setAttribute('stroke', '#b45309');
      line.setAttribute('stroke-dasharray', '4 3');
      line.setAttribute('fill', 'none');
      svg.append(line);
    }
  }
}

// ---------- inspector ----------
function field(label, input) {
  const l = elt('label', 'field');
  l.append(elt('span', '', label), input);
  return l;
}

function renderInspector() {
  const ff = el('flow-fields');
  ff.replaceChildren();
  const id = document.createElement('input');
  id.type = 'text';
  id.value = state.flow.id ?? '';
  id.addEventListener('input', () => (state.flow.id = id.value));
  ff.append(field('id', id));
  const ver = document.createElement('input');
  ver.type = 'number';
  ver.value = String(state.flow.version ?? 1);
  ver.addEventListener('input', () => (state.flow.version = Number(ver.value) || 1));
  ff.append(field('version', ver));
  const entry = document.createElement('select');
  entry.append(new Option('（未设）', ''));
  for (const n of state.flow.nodes) entry.append(new Option(n.id, n.id));
  entry.value = state.flow.entry ?? '';
  entry.addEventListener('change', () => {
    state.flow.entry = entry.value || null;
    render();
  });
  ff.append(field('entry', entry));
  const hint = elt('p', 'muted', `${state.flow.nodes.length} 个节点，${state.flow.edges.length} 条边。双击节点标题把它设为 entry。`);
  ff.append(hint);

  const box = el('selection');
  box.replaceChildren();
  if (!state.sel) {
    box.append(elt('p', 'muted', '点节点或连线编辑；拖块库到画布添加节点；拖节点右圆点到另一节点左圆点连线。'));
    return;
  }
  if (state.sel.kind === 'node') renderNodeInspector(box, state.flow.nodes.find((n) => n.id === state.sel.id));
  else renderEdgeInspector(box, state.sel.index);
}

function textAreaFor(obj, onChange) {
  const ta = document.createElement('textarea');
  ta.value = obj && Object.keys(obj).length ? exportSubset(obj) : '';
  ta.placeholder = 'k: v 每行一项（与 YAML 写法相同）';
  ta.addEventListener('change', () => {
    try {
      onChange(parseMapping(ta.value));
      ta.classList.remove('invalid');
    } catch (e) {
      ta.classList.add('invalid');
      say(`参数解析失败：${e.message}`, true);
    }
  });
  return ta;
}

function renderNodeInspector(box, n) {
  if (!n) return;
  const nid = document.createElement('input');
  nid.type = 'text';
  nid.value = n.id;
  nid.addEventListener('change', () => {
    const next = nid.value.trim();
    if (!next) return;
    if (state.flow.nodes.some((o) => o !== n && o.id === next)) {
      say(`节点 id「${next}」已存在`, true);
      nid.value = n.id;
      return;
    }
    for (const e of state.flow.edges) {
      if (e.from === n.id) e.from = next;
      if (e.to === n.id) e.to = next;
    }
    if (state.flow.entry === n.id) state.flow.entry = next;
    n.id = next;
    state.sel = { kind: 'node', id: next };
    render();
  });
  box.append(field('节点 id', nid));
  const uses = document.createElement('select');
  uses.append(new Option('（未选块）', ''));
  for (const b of state.blocks) uses.append(new Option(b.ref, b.ref));
  if (n.uses && !state.blocks.some((b) => b.ref === n.uses)) uses.append(new Option(`${n.uses}（块库未找到）`, n.uses));
  uses.value = n.uses ?? '';
  uses.addEventListener('change', () => {
    n.uses = uses.value;
    render();
  });
  box.append(field('uses（块）', uses));
  const blk = state.blocks.find((b) => b.ref === n.uses);
  if (blk) box.append(elt('p', 'muted', `输入：${Object.entries(blk.inputs ?? {}).map(([k, v]) => `${k}:${v?.type ?? '?'}`).join('，') || '无'}；输出：${Object.keys(blk.outputs ?? {}).join('，') || '无'}`));
  box.append(field('with（参数）', textAreaFor(n.with, (v) => ((n.with = v), render()))));
  for (const [k, v] of Object.entries(n.extra ?? {})) {
    if (v !== null && typeof v === 'object') {
      box.append(field(`${k}（结构）`, textAreaFor(v, (nv) => ((n.extra[k] = nv), render()))));
    } else {
      const inp = document.createElement('input');
      inp.type = 'text';
      inp.value = String(v);
      inp.addEventListener('change', () => {
        n.extra[k] = inp.value;
        render();
      });
      box.append(field(k, inp));
    }
  }
  const row = elt('div', 'row');
  const setEntry = elt('button', '', '设为 entry');
  setEntry.addEventListener('click', () => {
    state.flow.entry = n.id;
    render();
  });
  const del = elt('button', 'danger', '删除节点');
  del.addEventListener('click', () => {
    state.flow.nodes = state.flow.nodes.filter((o) => o !== n);
    state.flow.edges = state.flow.edges.filter((e) => e.from !== n.id && e.to !== n.id);
    if (state.flow.entry === n.id) state.flow.entry = state.flow.nodes[0]?.id ?? null;
    state.sel = null;
    render();
  });
  row.append(setEntry, del);
  box.append(row);
}

function renderEdgeInspector(box, idx) {
  const e = state.flow.edges[idx];
  if (!e) return;
  box.append(elt('p', '', `${e.from} → ${e.to}`));
  const fields = ['id', 'on', 'max_iterations', 'on_exhausted', ...Object.keys(e).filter((k) => !['id', 'from', 'to', 'on', 'max_iterations', 'on_exhausted', 'ui'].includes(k))];
  for (const k of fields) {
    const v = e[k];
    if (k === 'on' || (v !== null && typeof v === 'object')) {
      box.append(field(`${k}（结构）`, textAreaFor(v, (nv) => ((e[k] = Object.keys(nv).length ? nv : null), render()))));
    } else {
      const inp = document.createElement('input');
      inp.type = k === 'max_iterations' ? 'number' : 'text';
      inp.value = v === null || v === undefined ? '' : String(v);
      inp.placeholder = k === 'max_iterations' || k === 'on_exhausted' ? 'P0.5 字段（照实导出，校验器会报 E_P0_UNSUPPORTED）' : '';
      inp.addEventListener('change', () => {
        if (inp.value === '') e[k] = null;
        else if (k === 'max_iterations') e[k] = Number(inp.value);
        else e[k] = inp.value;
        render();
      });
      box.append(field(k, inp));
    }
  }
  const row = elt('div', 'row');
  const rev = elt('button', '', '反向');
  rev.addEventListener('click', () => {
    [e.from, e.to] = [e.to, e.from];
    render();
  });
  const del = elt('button', 'danger', '删除连线');
  del.addEventListener('click', () => {
    state.flow.edges.splice(idx, 1);
    state.sel = null;
    render();
  });
  row.append(rev, del);
  box.append(row);
}

// `k: v` per line, parsed with the same reader the flow uses for `with:`.
function parseMapping(text) {
  const src = String(text);
  if (!src.trim()) return {};
  const wrapped = src
    .split('\n')
    .filter((l) => l.trim())
    .map((l) => (/^\s/.test(l) ? l : `  ${l.trim()}`))
    .join('\n');
  const parsed = parseMappingViaFlow(wrapped);
  if (parsed === null) throw new Error('不是 「k: v」 形式');
  return parsed;
}

function parseMappingViaFlow(body) {
  const doc = `nodes:\n  - id: x\n    with:\n${body.split('\n').map((l) => '  ' + l).join('\n')}\n`;
  try {
    const model = parseFlow(doc);
    return model.nodes[0]?.with ?? {};
  } catch {
    return null;
  }
}

function exportSubset(obj) {
  // Reuse the flow exporter on a tiny flow so `with:` text matches YAML.
  const tiny = { id: 'x', version: 1, entry: null, nodes: [{ id: 'x', uses: '', with: obj, extra: {}, ui: null }], edges: [], extra: {} };
  const lines = exportFlow(tiny).split('\n');
  const start = lines.findIndex((l) => l === '    with:');
  if (start < 0) return '';
  const out = [];
  for (const l of lines.slice(start + 1)) {
    if (!l.startsWith('      ')) break;
    out.push(l.slice(6));
  }
  return out.join('\n');
}

// ---------- canvas events ----------
canvas.addEventListener('dragover', (e) => {
  e.preventDefault();
  e.dataTransfer.dropEffect = 'copy';
});

canvas.addEventListener('drop', (e) => {
  e.preventDefault();
  const ref = e.dataTransfer.getData('text/plain');
  const blk = state.blocks.find((b) => b.ref === ref);
  if (!blk) return;
  const rect = canvas.getBoundingClientRect();
  const n = addNode(blk, (e.clientX - rect.left) / state.zoom - NODE_W / 2, (e.clientY - rect.top) / state.zoom - NODE_H / 2);
  state.sel = { kind: 'node', id: n.id };
  render();
});

function addNode(blk, x, y) {
  const base = blk.id.replace(/[^a-z0-9]/g, '');
  let id = state.flow.nodes.some((n) => n.id === base) ? `${base}-${state.nextId}` : base;
  while (state.flow.nodes.some((n) => n.id === id)) id = `${base}-${state.nextId++}`;
  const node = { id, uses: blk.ref, with: defaultInputs(blk), extra: {}, ui: { x: Math.max(0, Math.round(x)), y: Math.max(0, Math.round(y)) } };
  state.flow.nodes.push(node);
  if (!state.flow.entry) state.flow.entry = id;
  return node;
}

function defaultInputs(blk) {
  // Inputs are bound from `{{input.<name>}}` when the block has a required
  // input named `request` (matches flows/main.yaml); nothing else is invented.
  return blk.inputs?.request ? { request: '{{input.request}}' } : {};
}

canvas.addEventListener('pointerdown', (e) => {
  const isNode = e.target.closest('.node');
  if (!isNode) {
    state.sel = null;
    render();
  }
});

nodesLayer.addEventListener('pointerdown', (e) => {
  const out = e.target.closest('.port.out');
  if (!out) return;
  e.preventDefault();
  e.stopPropagation();
  const from = out.dataset.out;
  const rect = canvas.getBoundingClientRect();
  state.linking = { from, x: (e.clientX - rect.left) / state.zoom, y: (e.clientY - rect.top) / state.zoom };
  canvas.classList.add('linking');
  renderEdges();
});

nodesLayer.addEventListener('pointerup', (e) => {
  const inp = e.target.closest('.port.in');
  if (!state.linking || !inp) return;
  const from = state.linking.from;
  const to = inp.dataset.in;
  state.linking = null;
  canvas.classList.remove('linking');
  if (from !== to) {
    if (!state.flow.edges.some((x) => x.from === from && x.to === to)) state.flow.edges.push({ id: null, from, to });
    state.sel = { kind: 'edge', index: state.flow.edges.length - 1 };
  }
  render();
});

window.addEventListener('pointermove', (e) => {
  if (!state.linking) return;
  const rect = canvas.getBoundingClientRect();
  state.linking.x = (e.clientX - rect.left) / state.zoom;
  state.linking.y = (e.clientY - rect.top) / state.zoom;
  renderEdges();
});

window.addEventListener('pointerup', () => {
  if (state.linking) {
    state.linking = null;
    canvas.classList.remove('linking');
    renderEdges();
  }
});

canvas.addEventListener('keydown', (e) => {
  if (e.key !== 'Delete' && e.key !== 'Backspace') return;
  if (!state.sel) return;
  if (e.target !== canvas) return;
  e.preventDefault();
  if (state.sel.kind === 'edge') {
    state.flow.edges.splice(state.sel.index, 1);
  } else {
    const id = state.sel.id;
    state.flow.nodes = state.flow.nodes.filter((n) => n.id !== id);
    state.flow.edges = state.flow.edges.filter((x) => x.from !== id && x.to !== id);
    if (state.flow.entry === id) state.flow.entry = state.flow.nodes[0]?.id ?? null;
  }
  state.sel = null;
  render();
});

